import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
const fallback = JSON.parse(readFileSync(new URL("../program-ids.json", import.meta.url), "utf8"));
const address = (name) => {
 const keypair = new URL(`../target/deploy/${name}_program-keypair.json`, import.meta.url);
 return existsSync(keypair) ? execFileSync("solana-keygen", ["pubkey", keypair.pathname], { encoding: "utf8" }).trim() : fallback[name];
};
const ids = { powerpay: address("powerpay"), powerchain: address("powerchain") };
writeFileSync(new URL("../program-ids.json", import.meta.url), JSON.stringify(ids, null, 2)+"\n");
writeFileSync(new URL("../src/program-ids.ts", import.meta.url), `/** Generated by scripts/sync-program-ids.mjs. */\nexport const POWERPAY_PROGRAM_ID = "${ids.powerpay}";\nexport const POWERCHAIN_PROGRAM_ID = "${ids.powerchain}";\n`);
console.log(ids);
